"""CAN protocol specification (single source for C++ header + Python codec).

Bus: classic CAN 2.0A, 11-bit IDs, 1 Mbit/s, little-endian payloads.

  ID                      dir          payload
  0x000                   brain->all   command  [cmd u8, node_mask u8]
  0x080                   brain->all   heartbeat/sync [counter u16, t_ms u32, flags u8]
  0x100 + node*8 + j      brain->node  joint setpoint
  0x200 + node*8 + j      node->brain  joint state
  0x300 + node            node->brain  node status
  0x380 + node            node->brain  joint fault words (2x u32: joints 0-3 / 4-7 packed 8 bit each)
  0x3F0                   hub->brain   HPU status
  0x3F1                   hub->brain   IMU quaternion (4x i16, 1/16384)
"""
from __future__ import annotations

import struct

BITRATE = 1_000_000
ID_CMD = 0x000
ID_SYNC = 0x080
ID_SETPOINT = 0x100
ID_STATE = 0x200
ID_STATUS = 0x300
ID_JFAULT = 0x380
ID_HPU = 0x3F0
ID_IMU = 0x3F1

CMD = {"NONE": 0, "ARM": 1, "RUN": 2, "DISARM": 3, "CLEAR_FAULT": 4, "ESTOP": 5}
NODE_STATE = {0: "BOOT", 1: "IDLE", 2: "ARMED", 3: "RUNNING", 4: "HOLD", 5: "FAULT", 6: "ESTOP"}
MODE = {"OFF": 0, "HOLD": 1, "POSITION": 2, "IMPEDANCE": 3, "FORCE": 4}

# message layouts: (name, struct format, [(field, scale)])
MESSAGES = {
    "setpoint": ("<hhhBB", [("q_ref", 1e-4), ("qd_ref", 1e-3), ("tau_ff", 1e-2), ("kp_scale", 1 / 100), ("mode_kd", 1)]),
    "state": ("<hhhBB", [("q", 1e-4), ("qd", 1e-3), ("tau", 1e-2), ("p_a", 0.25e5), ("p_b", 0.25e5)]),
    "status": ("<BBHHh", [("state", 1), ("joint_count", 1), ("faults", 1), ("p_supply", 1e3), ("temp", 1e-2)]),
    "hpu": ("<BBHBbH", [("state", 1), ("faults", 1), ("p_supply", 1e3), ("duty", 1 / 250), ("oil_temp", 1), ("vbat", 1e-3)]),
}


def setpoint_id(node: int, joint: int) -> int:
    return ID_SETPOINT + node * 8 + joint


def state_id(node: int, joint: int) -> int:
    return ID_STATE + node * 8 + joint


def _clip(v, fmt):
    lim = {"h": (-32768, 32767), "H": (0, 65535), "B": (0, 255), "b": (-128, 127)}[fmt]
    return int(max(lim[0], min(lim[1], round(v))))


def pack(kind: str, **vals) -> bytes:
    fmt, fields = MESSAGES[kind]
    codes = fmt[1:]
    raw = [_clip(vals.get(n, 0) / sc, c) for (n, sc), c in zip(fields, codes)]
    return struct.pack(fmt, *raw)


def unpack(kind: str, data: bytes) -> dict:
    fmt, fields = MESSAGES[kind]
    raw = struct.unpack(fmt, data[:struct.calcsize(fmt)])
    return {n: r * sc for (n, sc), r in zip(fields, raw)}


def pack_setpoint(q_ref, qd_ref=0.0, tau_ff=0.0, kp_scale=1.0, kd_scale=1.0, mode="IMPEDANCE") -> bytes:
    """mode_kd byte: high 3 bits = mode, low 5 bits = kd_scale * 16 (0..1.94)."""
    mk = (MODE[mode] << 5) | max(0, min(31, round(kd_scale * 16)))
    return pack("setpoint", q_ref=q_ref, qd_ref=qd_ref, tau_ff=tau_ff, kp_scale=kp_scale, mode_kd=mk)


def pack_cmd(cmd: str, node_mask: int = 0xFF) -> bytes:
    return struct.pack("<BB", CMD[cmd], node_mask)


def pack_sync(counter: int, t_ms: int, flags: int = 0) -> bytes:
    return struct.pack("<HIB", counter & 0xFFFF, t_ms & 0xFFFFFFFF, flags)


def c_header() -> str:
    L = ["// GENERATED by hx/codegen.py from hx/protocol.py - do not edit.", "#pragma once", "#include <math.h>", "#include <stdint.h>",
         "#include <string.h>", "", "namespace hx { namespace can {", "",
         f"constexpr uint32_t kBitrate = {BITRATE};"]
    for k, v in (("kIdCmd", ID_CMD), ("kIdSync", ID_SYNC), ("kIdSetpoint", ID_SETPOINT), ("kIdState", ID_STATE),
                 ("kIdStatus", ID_STATUS), ("kIdJointFault", ID_JFAULT), ("kIdHpu", ID_HPU), ("kIdImu", ID_IMU)):
        L.append(f"constexpr uint16_t {k} = 0x{v:03X};")
    L += ["", "enum Cmd : uint8_t { " + ", ".join(f"CMD_{k} = {v}" for k, v in CMD.items()) + " };", ""]
    for kind, (fmt, fields) in MESSAGES.items():
        ctype = {"h": "int16_t", "H": "uint16_t", "B": "uint8_t", "b": "int8_t"}
        L.append(f"struct __attribute__((packed)) {kind.capitalize()}Raw {{")
        for (n, sc), c in zip(fields, fmt[1:]):
            L.append(f"    {ctype[c]} {n};   // scale {sc:g}")
        L.append("};")
        L.append(f"static_assert(sizeof({kind.capitalize()}Raw) <= 8, \"CAN frame\");")
        for (n, sc), c in zip(fields, fmt[1:]):
            L.append(f"constexpr float k{kind.capitalize()}_{n} = {float(sc)!r}f;")
        L.append("")
    L += ["inline uint16_t setpoint_id(uint8_t node, uint8_t j) { return kIdSetpoint + node * 8 + j; }",
          "inline uint16_t state_id(uint8_t node, uint8_t j) { return kIdState + node * 8 + j; }",
          "inline int16_t sat16(float v) { return v > 32767.f ? 32767 : (v < -32768.f ? -32768 : (int16_t)lrintf(v)); }",
          "inline uint8_t sat8(float v) { return v > 255.f ? 255 : (v < 0.f ? 0 : (uint8_t)lrintf(v)); }",
          "", "} }  // namespace hx::can", ""]
    return "\n".join(L)
